#!/usr/bin/env bash
# Sourced, not run: the local sync stack's secrets and settings, shared by utils/stack_up.sh,
# utils/stack_down.sh, utils/sync_local.sh and utils/sync_e2e_check.sh so all four agree.
#
# The two secrets are generated ONCE into var/stack-sync.env (var/ is gitignored; the file is
# 0600) and reused on every later call -- regenerating the enrollment secret would silently
# un-enroll the local talium-sync config, and regenerating the signing key would invalidate
# live session tokens. Delete the file to rotate both.
#
#   TALIUM_SESSION_SIGNING_KEY      talium-uploadd only; never given to the client
#   TALIUM_SYNC_ENROLLMENT_SECRET   the org's enrollment secret; talium-uploadd AND talium-sync
#   TALIUM_S3_PREFIX                not stored: cc/logs unless set in the caller's env ("" = root)
#   TALIUM_S3_KEY_BASE              derived from it: "cc/logs/" or ""

sync_env_file() {
  echo "$1/var/stack-sync.env"
}

# sync_env_init ROOT -- create the env file if absent, then export everything in it.
sync_env_init() {
  local root="$1" file
  file="$(sync_env_file "$root")"
  if [[ ! -f "$file" ]]; then
    mkdir -p "$(dirname "$file")"
    (
      umask 077
      {
        echo "# Local sync stack secrets. Generated by utils/_sync_env.sh; never commit."
        echo "TALIUM_SESSION_SIGNING_KEY=$(openssl rand -hex 48)"
        echo "TALIUM_SYNC_ENROLLMENT_SECRET=$(openssl rand -hex 32)"
      } >"$file"
    )
    echo "[sync] generated local secrets in ${file}"
  fi
  sync_env_load "$root"
}

# sync_env_load ROOT -- export the env file if it exists; returns 1 if it does not.
sync_env_load() {
  local file
  file="$(sync_env_file "$1")"
  [[ -f "$file" ]] || return 1
  set -a
  # shellcheck disable=SC1090
  source "$file"
  set +a
  # `-` not `:-`: an explicitly empty prefix means the bucket root and must survive.
  export TALIUM_S3_PREFIX="${TALIUM_S3_PREFIX-cc/logs}"
  # The same prefix as tusd's object prefix / the collector's sweep root want it: slashes
  # trimmed, one trailing slash, "" for the bucket root (staging.NormalizePrefix's rule).
  local base="${TALIUM_S3_PREFIX#/}"
  base="${base%/}"
  export TALIUM_S3_KEY_BASE="${base:+${base}/}"
  export TALIUM_ORG_ID="${TALIUM_ORG_ID:-local-dev}"
}
