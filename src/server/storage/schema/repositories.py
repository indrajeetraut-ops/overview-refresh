"""repositories — the first-class repo entity (dashboard plan §3).

Deliberately lightweight: this is the JSONL/collector-derived half of repo identity, pulled
forward from `docs/modules/git-source.md`'s reserved `git_repos` design (G6) and scoped down
to what a transcript-evidence inference can support on its own -- no webhook receiver, no REST
backfill, no credentials. `repo_id` is generated by the same canonical scheme
(`src/common/git_ident.py`) that design already commits to, so a future GitHub App integration
can adopt these rows without a rename or a migration fork.
"""
from sqlalchemy.orm import Mapped, mapped_column

from .base import Base, jsb, ts


class Repository(Base):
    __tablename__ = "repositories"
    # The git_ident canonical form (`github:<owner>/<name>`, `git:<host>/<owner>/<name>`) for
    # a `git_remote`/`pr_link`-tier id, or `local:<repo_key>` for a `path`-tier one -- kept in
    # the same column, never colliding, since the two schemes' prefixes are disjoint.
    repo_id: Mapped[str] = mapped_column(primary_key=True)
    kind: Mapped[str]                              # git_remote | local_path
    label: Mapped[str]                              # display string: owner/name or path basename
    first_seen_at: Mapped[ts]
    last_seen_at: Mapped[ts]
    # Catch-all, additive (same convention as the reserved git_artifacts.info): the raw
    # remote URL/provenance tier that produced this row, room for whatever a future pass adds
    # without a migration.
    info: Mapped[jsb]
